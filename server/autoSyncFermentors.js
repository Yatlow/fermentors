// GET SINGLE FERMENTOR FROM FIRESTORE
// ============================================================

function getFermentorFromFirestore(
  projectId,
  fermentorId
) {

  const url =
    "https://firestore.googleapis.com/v1/projects/" +
    projectId +
    "/databases/(default)/documents/fermentors/" +
    encodeURIComponent(
      fermentorId
    );


  const response =
    UrlFetchApp.fetch(
      url,
      {

        method: "get",

        headers: {

          Authorization:
            "Bearer " +
            ScriptApp.getOAuthToken()

        },

        muteHttpExceptions:
          true

      }
    );


  const code =
    response.getResponseCode();


  if (
    code === 404
  ) {

    return null;

  }


  if (
    code < 200 ||
    code >= 300
  ) {

    throw new Error(
      "Firestore get fermentor failed: " +
      code +
      " " +
      response.getContentText()
    );

  }


  const document =
    JSON.parse(
      response.getContentText()
    );


  const fields =
    document.fields || {};


  const normalized =
    {};


  for (
    const key in fields
  ) {

    normalized[key] =
      normalizeFirestoreValue(
        fields[key]
      );

  }


  return normalized;
}


