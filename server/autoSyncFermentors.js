// REFRESH SINGLE TANK
// ============================================================

function refreshSingleTank(
  fermentorID,
  sheetUrl
) {

  if (!fermentorID) {
    throw new Error(
      "Missing fermentorID"
    );
  }

  if (!sheetUrl) {
    throw new Error(
      "Missing sheetUrl"
    );
  }


  const projectId =
    FIREBASE_PROJECT_ID;


  // ==========================================================
  // READ GOOGLE SHEET
  // ==========================================================

  const brew =
    extractBrew(
      sheetUrl
    );


  if (
    !brew ||
    !brew.tankNumber
  ) {

    return {
      updated: false,
      reason: "no tankNumber"
    };

  }


  // ==========================================================
  // NEW CURRENT DATA
  // ==========================================================
  //
  // ההגנה על kegs / crates / totalLiters / shrinkagePercent
  // מתבצעת בתוך updateFermentorDocument עצמו - אין צורך
  // ב-merge כפול כאן.
  // ==========================================================

  const incomingCurrentData =
    brew.currentData || {};


  // ==========================================================
  // NEW DATA
  // ==========================================================

  const newData = {

    tankNumber:
      String(
        brew.tankNumber
      ).trim(),

    tankStatus:
      brew.tankStatus === "TRUE",

    batchNumber:
      brew.batchNumber || null,

    beerStyle:
      brew.beerStyle || null,

    brewDate:
      brew.brewDate || null,

    beerVolume:
      brew.beerVolume || null,

    currentData:
      incomingCurrentData,

    sheetUrl:
      brew.sheetUrl || null,

    uid:
      fermentorID,

    startingPlato:
      brew.startingPlato || null
  };


  // ==========================================================
  // LOCAL CACHE
  // ==========================================================

  const cacheKey =
    "fermentor:" +
    fermentorID;


  const changed =
    hasChangedLocally_(
      cacheKey,
      newData
    );


  // ==========================================================
  // LATEST MEASUREMENT
  // ==========================================================

  let latestMeasurementWrote =
    false;


  if (
    newData.batchNumber
  ) {

    try {

      latestMeasurementWrote =
        writeLatestMeasurementIfChanged_(
          projectId,
          newData.batchNumber,
          sheetUrl
        );

    } catch (
    err
    ) {

      Logger.log(
        "refreshSingleTank measurement write error: " +
        err.message
      );

    }

  }


  // ==========================================================
  // NO CHANGE
  // ==========================================================

  if (!changed) {

    return {
      updated: false,
      latestMeasurementWrote:
        latestMeasurementWrote
    };

  }


  // ==========================================================
  // UPDATE
  // ==========================================================

  newData.updatedAt =
    new Date();


  updateFermentorDocument(
    projectId,
    fermentorID,
    newData
  );


  return {
    updated: true,
    latestMeasurementWrote:
      latestMeasurementWrote
  };
}

